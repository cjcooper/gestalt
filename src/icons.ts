export type FileKind = "tofu" | "vars" | "env" | "text" | "other";

export function fileKind(name: string): FileKind {
  const n = name.toLowerCase();
  if (n === ".gestalt.env") return "env";
  if (n.endsWith(".tf") || n.endsWith(".tofu") || n.endsWith(".hcl")) return "tofu";
  if (n.endsWith(".tfvars") || n.endsWith(".tfvars.json")) return "vars";
  if (/\.(md|txt|json|ya?ml|toml|sh|mk)$/.test(n) || n === "makefile") return "text";
  return "other";
}

export function fileIcon(kind: FileKind): string {
  switch (kind) {
    case "tofu":
      return icons.fileCode;
    case "vars":
      return icons.fileVars;
    case "env":
      return icons.key;
    case "text":
      return icons.fileText;
    default:
      return icons.file;
  }
}
